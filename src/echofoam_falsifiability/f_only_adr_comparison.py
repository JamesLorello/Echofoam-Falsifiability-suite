"""Held-out comparison with shared-coefficient, F-only ADR models.

All target trajectories are generated by the declared local-memory toy
kernel. The comparison asks whether conventional F-only advection-diffusion-
reaction models can predict those held-out toy trajectories from the shared
present field alone. It is a model-class check, not physical validation.
"""

